const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE_SCRIPT = path.join(ROOT, "scripts/linkcheck.mjs");
const SOURCE_PARSER = path.join(ROOT, "scripts/vendor/commonmark.cjs");
const POPULATION_RELATIVE = "test/support/linkcheck-population.mjs";
const FAMILY = [
  "seal-check",
  "seal-demo",
  "seal-live-demo",
  "seal-verify-action",
  "seal-assurance-kit",
  "mcp-seal-dev",
];

function sha256(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

function counts(internalOccurrences, externalOccurrences = 0) {
  return { internalOccurrences, externalOccurrences };
}

function populationSource({ fileOccurrences, fileOccurrencesHighWaterMarks = fileOccurrences, internalOccurrences }) {
  return [
    "// Generated by node scripts/linkcheck.mjs --write; review by rerunning that command.",
    "// The separate-source target cross-check lives in test/linkcheck.test.mjs and",
    "// cannot be refreshed from LINKCHECK_REPORT_SCANNED_TARGETS. It is deliberately",
    "// described as a cross-check; docs/assurance/linkcheck-population-control.md",
    "// records its shared blind spots.",
    "// High-water marks never move down automatically; accepted shrink history stays review-visible.",
    "export default {",
    "  populationRule: 1,",
    `  internalOccurrences: ${internalOccurrences},`,
    "  externalOccurrences: 0,",
    `  internalOccurrencesHighWaterMark: ${internalOccurrences},`,
    "  externalOccurrencesHighWaterMark: 0,",
    `  fileOccurrences: ${JSON.stringify(fileOccurrences, null, 2).replace(/^/gm, "  ")},`,
    `  fileOccurrencesHighWaterMarks: ${JSON.stringify(fileOccurrencesHighWaterMarks, null, 2).replace(/^/gm, "  ")},`,
    "  shrinkHistory: [",
    "  ],",
    "};",
    "",
  ].join("\n");
}

function workspace({ pages, population }) {
  const space = mkdtempSync(path.join(tmpdir(), "seal-linkgen8-"));
  const runner = path.join(space, "runner");
  const tree = path.join(space, "tree");
  const script = path.join(runner, "scripts/linkcheck.mjs");
  const record = path.join(runner, POPULATION_RELATIVE);
  mkdirSync(path.dirname(script), { recursive: true });
  mkdirSync(path.join(runner, "scripts/vendor"), { recursive: true });
  mkdirSync(path.dirname(record), { recursive: true });
  mkdirSync(path.join(tree, "spine"), { recursive: true });
  for (const repo of FAMILY) mkdirSync(path.join(tree, ".family", repo), { recursive: true });
  copyFileSync(SOURCE_SCRIPT, script);
  copyFileSync(SOURCE_PARSER, path.join(runner, "scripts/vendor/commonmark.cjs"));
  writeFileSync(path.join(runner, "package.json"), "{\"type\":\"module\"}\n");
  writeFileSync(path.join(runner, "mock-fetch.mjs"), [
    "globalThis.fetch = async () => ({",
    "  ok: true,",
    "  body: { cancel: async () => {} },",
    "});",
    "",
  ].join("\n"));
  writeFileSync(record, population);
  writeFileSync(path.join(tree, "spine/demo.cjs"), "// https://velvetmonkey.github.io/seal-check/\n");
  for (const [name, contents] of Object.entries(pages)) {
    const file = path.join(tree, name);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, contents);
  }
  const run = (...args) => spawnSync(process.execPath, [
    "--import", path.join(runner, "mock-fetch.mjs"),
    script,
    "--write",
    ...args,
    "--root", tree,
  ], { cwd: runner, encoding: "utf8" });
  return {
    space,
    tree,
    record,
    run,
    cleanup: () => rmSync(space, { recursive: true, force: true }),
  };
}

function basicPages(readme = "Required https://velvetmonkey.github.io/seal-check/\n[one](target.md)\n") {
  return { "README.md": readme, "target.md": "target\n" };
}

function basicFiles(readmeCount = 1, extra = {}) {
  return {
    "README.md": counts(readmeCount),
    ...extra,
    "target.md": counts(0),
  };
}

function output(result) {
  return `${result.stdout}${result.stderr}`;
}

test("defect 1: a named shrink does not sequentially re-baseline an unflagged write", () => {
  const files = basicFiles(2);
  const space = workspace({
    pages: basicPages("Required https://velvetmonkey.github.io/seal-check/\n[one](target.md)\n[two](target.md)\n"),
    population: populationSource({ fileOccurrences: files, internalOccurrences: 2 }),
  });
  try {
    writeFileSync(path.join(space.tree, "README.md"), basicPages()["README.md"]);
    const accepted = space.run("--allow-shrink", "README.md");
    assert.equal(accepted.status, 0, output(accepted));
    const unflagged = space.run();
    assert.equal(unflagged.status, 1, output(unflagged));
    assert.match(unflagged.stderr, /README\.md/);
  } finally {
    space.cleanup();
  }
});

test("defect 2: comments and duplicate keys cannot poison a recorded file count", () => {
  const files = basicFiles(1, { "loser.md": counts(1) });
  const base = populationSource({ fileOccurrences: files, internalOccurrences: 2 });
  const commentSpace = workspace({
    pages: { ...basicPages(), "loser.md": "[one](target.md)\n" },
    population: base.replace("export default {", "// loser.md internalOccurrences: 0\nexport default {"),
  });
  try {
    writeFileSync(path.join(commentSpace.tree, "loser.md"), "no links\n");
    writeFileSync(path.join(commentSpace.tree, "README.md"), `${basicPages()["README.md"]}[two](target.md)\n`);
    const result = commentSpace.run();
    assert.equal(result.status, 1, output(result));
  } finally {
    commentSpace.cleanup();
  }

  const duplicateEntry = [
    '    "loser.md": {',
    '      "internalOccurrences": 0,',
    '      "externalOccurrences": 0',
    "    },",
  ].join("\n");
  const recordedLoser = [
    '    "loser.md": {',
    '      "internalOccurrences": 1,',
    '      "externalOccurrences": 0',
    "    },",
  ].join("\n");
  const duplicateSpace = workspace({
    pages: { ...basicPages(), "loser.md": "no links\n" },
    population: base.replace(recordedLoser, `${recordedLoser}\n${duplicateEntry}`),
  });
  try {
    writeFileSync(path.join(duplicateSpace.tree, "README.md"), `${basicPages()["README.md"]}[two](target.md)\n`);
    const result = duplicateSpace.run();
    assert.equal(result.status, 1, output(result));
    assert.match(result.stderr, /duplicate key.*loser\.md/);
  } finally {
    duplicateSpace.cleanup();
  }
});

