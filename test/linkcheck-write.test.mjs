test("defect 4: an absent, empty, or wrong-typed record refuses", () => {
  const files = basicFiles();
  const source = populationSource({ fileOccurrences: files, internalOccurrences: 1 });
  for (const variant of ["absent", "empty", "wrong-typed"]) {
    const space = workspace({ pages: basicPages(), population: source });
    try {
      if (variant === "absent") rmSync(space.record);
      else if (variant === "empty") writeFileSync(space.record, "");
      else writeFileSync(space.record, "export default [];\n");
      const result = space.run();
      assert.equal(result.status, 1, `${variant}: ${output(result)}`);
      assert.match(output(result), /REFUSE/, `${variant} must be a named refusal`);
    } finally {
      space.cleanup();
    }
  }
});

